/// Shared dynamic JSON value for open-ended schema metadata, tool inputs, provider options,
/// and dynamic payloads across `OpenCodeSchema` and `OpenCodeProtocol`.
/// 100% pure Swift standard library (`Sendable`, `Hashable`, `Codable`, zero OS imports).
public enum JSONValue: Equatable, Hashable, Sendable, Codable {
    case null
    case bool(Bool)
    case int(Int64)
    case double(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])

    public init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        if container.decodeNil() {
            self = .null
        } else if let b = try? container.decode(Bool.self) {
            self = .bool(b)
        } else if let i = try? container.decode(Int64.self) {
            self = .int(i)
        } else if let d = try? container.decode(Double.self) {
            self = .double(d)
        } else if let s = try? container.decode(String.self) {
            self = .string(s)
        } else if let arr = try? container.decode([JSONValue].self) {
            self = .array(arr)
        } else if let obj = try? container.decode([String: JSONValue].self) {
            self = .object(obj)
        } else {
            throw DecodingError.dataCorruptedError(in: container, debugDescription: "Unsupported JSONValue")
        }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.singleValueContainer()
        switch self {
        case .null: try container.encodeNil()
        case .bool(let b): try container.encode(b)
        case .int(let i): try container.encode(i)
        case .double(let d): try container.encode(d)
        case .string(let s): try container.encode(s)
        case .array(let arr): try container.encode(arr)
        case .object(let obj): try container.encode(obj)
        }
    }
}

/// Core location coordinate pairing a workspace directory with an optional workspace ID.
public struct OpenCodeLocation: Equatable, Hashable, Sendable, Codable {
    public let directory: String
    public let workspaceID: WorkspaceID?

    public init(directory: String, workspaceID: WorkspaceID? = nil) {
        self.directory = directory
        self.workspaceID = workspaceID
    }
}
