        )

        let client = OpenCode.make(ClientOptions(baseUrl: "http://127.0.0.1:49374", transport: transport))

        do {
            _ = try await client.server.info()
            Issue.record("Expected ClientError(.unsupportedContentType)")
        } catch let err as ClientError {
            #expect(err.reason == .unsupportedContentType)
            #expect(err.statusCode == 400)
            let detail = try #require(err.detail)
            #expect(detail.contains("status 400"))
            #expect(detail.contains("content-type: text/plain"))
            #expect(detail.hasSuffix("…"))
            #expect(detail.count < longBody.count)
        }

        do {
            _ = try await client.server.pair()
            Issue.record("Expected ClientError(.unsupportedContentType) on missing content-type")
        } catch let err as ClientError {
            #expect(err.reason == .unsupportedContentType)
            #expect(err.statusCode == 200)
            let detail = try #require(err.detail)
            #expect(detail.contains("status 200"))
            #expect(detail.contains("content-type: <none>"))
            #expect(detail.contains("plain ok body"))
        }

        do {
            for try await _ in client.event.subscribe() {}
            Issue.record("Expected ClientError(.unsupportedContentType) on SSE missing content-type")
        } catch let err as ClientError {
            #expect(err.reason == .unsupportedContentType)
            #expect(err.statusCode == 200)
            #expect(err.detail == "status 200, content-type: <none>")
        }
