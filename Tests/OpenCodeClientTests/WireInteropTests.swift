    // MARK: - 1. RFC 7617 Standard Base64 Basic Auth

    @Test("ClientHTTPHeaders.basicAuthorization uses RFC 7617 standard padded Base64 across special chars & padding")
    func rfc7617BasicAuthorizationEncoding() throws {
        // Exact vectors verified against Node `Buffer.from(u + ":" + p).toString("base64")`
        let vectors: [(user: String, pass: String, expected: String)] = [
            // Length 15 (mod 3 == 0): no padding
            ("opencode", "secret", "Basic b3BlbmNvZGU6c2VjcmV0"),
            // Length 11 (mod 3 == 2): single '=' padding
            ("opencode", "pw", "Basic b3BlbmNvZGU6cHc="),
            // Length 10 (mod 3 == 1): double '==' padding
            ("opencode", "a", "Basic b3BlbmNvZGU6YQ=="),
            // Standard 43-char base64url password generated by OpenCode `randomBytes(32).toString("base64url")`:
            // 9 ("opencode:") + 43 = 52 bytes (52 % 3 == 1 -> ALWAYS ends with '==')
            (
                "opencode",
                "AbCdEfGhIjKlMnOpQrStUvWxYz0123456789-_AbCdE",
                "Basic b3BlbmNvZGU6QWJDZEVmR2hJaktsTW5PcFFyU3RVdld4WXowMTIzNDU2Nzg5LV9BYkNkRQ=="
            ),
            // Password containing '+', '/', '=', '-', '_', and ':' (RFC 7617 allows ':' in password)
            (
                "opencode",
                "p+w/1=2-3_4:5",
                "Basic b3BlbmNvZGU6cCt3LzE9Mi0zXzQ6NQ=="
            ),
            // Characters whose Base64 encoding emits BOTH '+' and '/' and padding '='/'==' (must NOT become '-'/'_' or lose '=')
            (
                "opencode",
                ">>>???a",
                "Basic b3BlbmNvZGU6Pj4+Pz8/YQ=="
            ),
            (
                "opencode",
                ">>>???ab",
                "Basic b3BlbmNvZGU6Pj4+Pz8/YWI="
            ),
            // UTF-8 multibyte password
            (
                "opencode",
                "✓ café",
                "Basic b3BlbmNvZGU64pyTIGNhZsOp"
            ),
        ]

        let specialDoublePad = ClientHTTPHeaders.basicAuthorization(username: "opencode", password: ">>>???a")
        #expect(specialDoublePad.contains("+"))
        #expect(specialDoublePad.contains("/"))
        #expect(specialDoublePad.hasSuffix("=="))

        let specialSinglePad = ClientHTTPHeaders.basicAuthorization(username: "opencode", password: ">>>???ab")
        #expect(specialSinglePad.contains("+"))
        #expect(specialSinglePad.contains("/"))
        #expect(specialSinglePad.hasSuffix("=") && !specialSinglePad.hasSuffix("=="))

        for vector in vectors {
            let header = ClientHTTPHeaders.basicAuthorization(username: vector.user, password: vector.pass)
            #expect(header == vector.expected, "Basic auth mismatch for password '\(vector.pass)'")

            // Must round-trip through strict RFC 4648 standard Base64 decoder (`base64ToBytes`),
            // matching upstream Effect `Base64.decodeString`.
            #expect(header.hasPrefix("Basic "))
            let token = String(header.dropFirst(6))
            #expect(token.count % 4 == 0, "RFC 7617 Base64 must be 4-char aligned with '=' padding")
            #expect(!token.contains("-"), "RFC 7617 Base64 must not use URL-safe '-'")
            #expect(!token.contains("_"), "RFC 7617 Base64 must not use URL-safe '_'")

            let decodedBytes = try base64ToBytes(token)
            let decodedText = String(decoding: decodedBytes, as: UTF8.self)
            #expect(decodedText == "\(vector.user):\(vector.pass)")

            // Verify `ClientServiceDiscovery.headers(for:)` uses the exact same RFC 7617 encoding
            let endpoint = ServiceEndpoint(
                url: "http://127.0.0.1:49374",
                auth: ServiceBasicAuth(username: vector.user, password: vector.pass)
            )
            #expect(headers(for: endpoint)?["authorization"] == vector.expected)
        }
    }

    // MARK: - 2. Real OpenCode 2.3.2 Service Discovery & Health Probe

    @Test("Service discovery reads 2.3.2 service.json and authenticates /api/info with strict RFC 7617 Base64")
    func serviceDiscovery232Interop() async throws {
        // 43-char base64url password + characters that yield '+'/'/'/'==' in Base64
        let password = "???>AbCdEfGhIjKlMnOpQrStUvWxYz0123456789-_A"
        let expectedAuth = "Basic " + bytesToBase64(Array("opencode:\(password)".utf8))
        #expect(expectedAuth.hasSuffix("=="))

        let fs = InMemoryFileSystem()
        let env = DictionaryEnvironment(
            variables: ["XDG_STATE_HOME": "/Users/dev/.local/state"],
            homeDirectory: "/Users/dev"
        )
        let serviceFile = fallback(environment: env)
        #expect(serviceFile == "/Users/dev/.local/state/opencode/service.json")

        let registrationJSON = """
        {"id":"svc_232_prod","version":"2.3.2","url":"http://127.0.0.1:49374","pid":48291,"password":"\(password)"}
        """
        try await fs.writeFile(Array(registrationJSON.utf8), to: serviceFile, createDirectories: true)

        // Strict server simulator matching upstream Effect `Base64.decodeString` (rejects unpadded or URL-safe Base64)
        let transport = MockHTTPTransport { request in
            guard request.method == "GET", request.url == "http://127.0.0.1:49374/api/info" else {
                return WireInteropFixtures.rawTextResponse(status: 404, body: "Not Found")
            }
            guard let auth = ClientHTTPHeaders.value(in: request.headers, for: "authorization"),
                  auth == expectedAuth
            else {
                return WireInteropFixtures.rawJSONResponse(status: 401, json: WireInteropFixtures.unauthorized232JSON)
            }
            return WireInteropFixtures.rawJSONResponse(status: 200, json: WireInteropFixtures.serverInfo232JSON)
        }

        let discovered = await PromiseService.discover(
            options: ServiceDiscoverOptions(),
            fileSystem: fs,
            transport: transport,
            environment: env
        )
        let endpoint = try #require(discovered)
        #expect(endpoint.url == "http://127.0.0.1:49374")
        #expect(endpoint.auth?.username == "opencode")
        #expect(endpoint.auth?.password == password)
        #expect(transport.requests.count == 1)
        #expect(transport.requests[0].headers["authorization"] == expectedAuth)

        // Probe when server is starting (503) vs failed (500) vs unauthorized (401)
        let info = ServiceInfo(id: "svc_232_prod", version: "2.3.2", url: "http://127.0.0.1:49374", pid: 48291, password: password)
        let startingTransport = MockHTTPTransport { _ in
            WireInteropFixtures.rawJSONResponse(status: 503, headers: ["retry-after": "1"], json: WireInteropFixtures.serverInfo232JSON)
        }
        let startingProbe = await probeResult(info, transport: startingTransport)
        #expect(startingProbe.service?.state == .waiting)
        #expect(startingProbe.service?.compatible == true)

        let unauthTransport = MockHTTPTransport { _ in
            WireInteropFixtures.rawJSONResponse(status: 401, json: WireInteropFixtures.unauthorized232JSON)
        }
        let unauthProbe = await probeResult(info, transport: unauthTransport)
        #expect(unauthProbe.service == nil)
        #expect(unauthProbe.timedOut == false)
    }

