    // MARK: - 4. Non-JSON Error Body Diagnostics & URL Query Joining

    @Test("responseError surfaces statusCode, content-type, and body snippet for non-JSON declared errors")
    func nonJSONDeclaredErrorDiagnostics() async throws {
        let transport = MockHTTPTransport { request in
            if request.url.hasSuffix("/api/info") {
                return WireInteropFixtures.rawTextResponse(
                    status: 401,
                    contentType: "text/plain",
                    body: "Unauthorized: invalid Basic credentials"
                )
            }
            if request.url.hasSuffix("/api/pair") {
                // Missing Content-Type header + empty body on declared 401
                return WireInteropFixtures.rawTextResponse(
                    status: 401,
                    contentType: nil,
                    body: ""
                )
            }
            if request.url.contains("/api/session/ses_proxy404") {
                return WireInteropFixtures.rawTextResponse(
                    status: 404,
                    contentType: "text/html; charset=utf-8",
                    body: "<html>\n  <body>404 Not Found</body>\n</html>"
                )
            }
            if request.url.contains("/api/session/ses_json401") {
                return WireInteropFixtures.rawJSONResponse(
                    status: 401,
                    json: WireInteropFixtures.unauthorized232JSON
                )
            }
            return WireInteropFixtures.rawTextResponse(status: 500, body: "unexpected")
        }

        let client = OpenCode.make(ClientOptions(baseUrl: "http://127.0.0.1:49374", transport: transport))

        // Plain-text 401 -> includes status 401, content-type, and body snippet
        do {
            _ = try await client.server.info()
            Issue.record("Expected ClientError(.unsupportedContentType)")
        } catch let err as ClientError {
            #expect(err.reason == .unsupportedContentType)
            #expect(err.statusCode == 401)
            let detail = try #require(err.detail)
            #expect(detail.contains("status 401"))
            #expect(detail.contains("content-type: text/plain"))
            #expect(detail.contains("body: Unauthorized: invalid Basic credentials"))
        }

        // Missing content-type + empty body on 401 -> never opaque nil detail
        do {
            _ = try await client.server.pair()
            Issue.record("Expected ClientError(.unsupportedContentType)")
        } catch let err as ClientError {
            #expect(err.reason == .unsupportedContentType)
            #expect(err.statusCode == 401)
            #expect(err.detail == "status 401, content-type: <none>")
        }

        // HTML 404 from reverse proxy -> includes status 404, content-type, and collapsed HTML snippet
        do {
            _ = try await client.session.get(SessionGetInput(sessionID: "ses_proxy404"))
            Issue.record("Expected ClientError(.unsupportedContentType)")
        } catch let err as ClientError {
            #expect(err.reason == .unsupportedContentType)
            #expect(err.statusCode == 404)
            let detail = try #require(err.detail)
            #expect(detail.contains("status 404"))
            #expect(detail.contains("content-type: text/html; charset=utf-8"))
            #expect(detail.contains("404 Not Found"))
        }

        // Valid JSON 401 with charset parameter -> decoded as typed UnauthorizedError
        do {
            _ = try await client.session.get(SessionGetInput(sessionID: "ses_json401"))
            Issue.record("Expected UnauthorizedError")
        } catch {
            #expect(isUnauthorizedError(error))
        }

        // ClientURLBuilder.join cleanly merges query params in both baseUrl, path, and explicit query
        let merged = ClientURLBuilder.join(
            baseUrl: "http://127.0.0.1:49374/proxy?a=1",
            path: "/api/session?limit=5",
            query: [("archived", .bool(false))]
        )
        #expect(merged == "http://127.0.0.1:49374/proxy/api/session?a=1&limit=5&archived=false")
    }

    @Test("responseError truncates long non-JSON bodies and decodeJSON/sse handle missing content-type")
